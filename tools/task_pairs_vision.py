#!/usr/bin/env python3
"""TASK_PAIRS_VISION.md (local, not committed): each copied vision cell that fails the vision zoo's internal line next
to the verdict of its task cell (`task-<cell>`, PLAN.md section Z5), from the cell JSONs.

    python3 tools/task_pairs_vision.py

The table puts runtimes side by side, so it is written on your disk only (.gitignore).
"""
import collections
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import zoo  # noqa: E402

Z1_REPO, Z1_COMMIT = "john-rocky/windows-zoo", "faa4019"
OUT = "TASK_PAIRS_VISION.md"


def failing_cells():
    out = {}
    for f in sorted(zoo.MODELS.glob("*/results/*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        ln = d.get("line") or {}
        if d.get("kind") == "vision" and d.get("role") is None and ln.get("kind") == "internal" and ln.get("pass") is False:
            out.setdefault(d["model"], []).append(d["cell"])
    return out


def main():
    fail = failing_cells()
    groups = collections.OrderedDict((k, []) for k in ("pass", "fail", "none"))
    count = collections.Counter()
    order = {m: zoo.recipe(zoo.MODELS / m)["model"].get("order", 10 ** 6) for m in fail}
    cell_order = ["ovnpu", "ovnpu_pre", "ovgpu", "cuda16", "cuda32"]
    for m in sorted(fail, key=lambda m: (order[m], m.lower())):
        for c in sorted(fail[m], key=lambda c: cell_order.index(c) if c in cell_order else 99):
            z1 = json.loads((zoo.MODELS / m / "results" / f"{c}.json").read_text(encoding="utf-8"))
            tp = zoo.MODELS / m / "results" / f"task-{c}.json"
            t = json.loads(tp.read_text(encoding="utf-8")) if tp.exists() else None
            z1_words = "; ".join(n["text"] for n in z1.get("note") or [] if n.get("rank") == 3) or \
                "; ".join((z1.get("line") or {}).get("fails") or []) or "FAIL"
            what = (f"{(t or z1)['runtime']['label']} · {(t or z1)['device']['label']} · "
                    f"{((t or z1).get('form') or {}).get('label') or '-'}")
            rec = ((t or {}).get("source") or {}).get("record")
            st = ((t or {}).get("run") or {}).get("state")
            ln = (t or {}).get("line") or {}
            if t is None:
                key, words, verdict = "none", "no task cell", "-"
            elif st == "not_run":
                key, words, verdict = "none", "not run (" + ((t["run"].get("why") or "").strip()) + ")", "not run"
            elif st != "ok":
                key, words, verdict = "none", "ERROR: " + (t["run"].get("error_line") or "")[:160], "error"
            elif ln.get("pass") is None:
                why = next((n["text"] for n in t.get("note") or [] if n.get("rank") == 2), None)
                key, words, verdict = "none", (ln.get("text") or why or "no verdict"), "no verdict"
            else:
                key = "pass" if ln["pass"] else "fail"
                words, verdict = ln.get("text") or "", "PASS" if ln["pass"] else "FAIL"
            count[verdict] += 1
            groups[key].append(f"| {m} | `{c}` | {what} | {z1_words.replace('|', '/')} | `{ln.get('id') or '-'}` | "
                               f"{verdict} | {words.replace('|', '/')} | " + (f"`{rec}`" if rec else "-") + " |")
    n = sum(count.values())
    head = ["# The vision cells that fail the internal line, judged on task lines", "",
            "Generated by `python3 tools/task_pairs_vision.py` from `models/<model>/results/<cell>.json` (each copied "
            "cell and its task cell `task-<cell>`); do not edit, do not commit (it puts runtimes side by side). The "
            f"cells: the vision zoo's ({Z1_REPO}@{Z1_COMMIT}) cells whose internal-agreement line failed, {n} cells of "
            f"{len(fail)} models, each judged again on its model's task line (PLAN.md section Z5, written before any "
            "run; each rule is on the model's card). One first pass on the PC (one run per input, untimed); the "
            "reference = the same fp32 ONNX file on the ONNX Runtime 1.31.1 CPU EP on the same inputs. The internal "
            "column is the copied cell's own words.", "",
            "Task line: " + ", ".join(f"{k} {count[k]}" for k in ("PASS", "FAIL", "no verdict", "error", "not run")
                                     if count[k]) + f" (of {n}).", ""]
    titles = {"pass": "## Internal line FAIL, task line PASS",
              "fail": "## Internal line FAIL, task line FAIL",
              "none": "## Not judged on the task line (why)"}
    hdr = ["| model | copied cell | runtime · device · form | internal line (copied) | task line | verdict | "
           "the task line's numbers | record |", "|---|---|---|---|---|---|---|---|"]
    out = head
    for k, rows in groups.items():
        out += [titles[k], ""] + ((hdr + rows) if rows else ["(none)"]) + [""]
    zoo.write_text(zoo.ROOT / OUT, "\n".join(out))
    print(f"{OUT}: {n} cells: " + ", ".join(f"{k} {v}" for k, v in count.items()))


if __name__ == "__main__":
    main()
