#!/usr/bin/env python3
"""TASK_PAIRS_LLM.md (local, not committed) from the cell JSONs: one line per copied LLM cell that passes only the
text-integrity line (86), its text-integrity verdict next to the verdict of its qa20 task cell (task-<cell>, PLAN.md
section Z6), or why that cell has none (an error, not run). Run after tools/results.py; the counts at the head are
this file's. The table puts runtimes side by side, so it is written on your disk only (.gitignore).

    python3 tools/task_pairs_llm.py [--note <model>/<cell>=<text> ...]
"""
import argparse
import collections
import datetime
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import zoo  # noqa: E402

MODELS = ["Qwen3-0.6B", "Qwen3-1.7B", "Qwen3-4B", "gemma-4-E2B-it", "gemma-4-E4B-it"]
EP_LINES = "raw/z6/foundry_ep_lines.txt"   # the Foundry Local daemon's log lines (grepped on the PC on 2026-11-10)
EP_LINE = re.compile(r"^foundry_local_[0-9-]+\.log:\d+: \[(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)\.\d+\] \[info\] model (\S+) "
                     r"applying explicit main decoder EP override: (\S+)")


def foundry_ep(t, lines):
    """the main decoder's EP the daemon logged for this Foundry cell's model id inside its run ("?" if not one line)"""
    argv = (t.get("source") or {}).get("argv") or []
    fid = argv[argv.index("--id") + 1] if "--id" in argv else None
    run = t.get("run") or {}
    if not fid or not run.get("started") or not run.get("ended"):
        return "?"
    t0 = datetime.datetime.fromisoformat(run["started"])
    t1 = datetime.datetime.fromisoformat(run["ended"])
    eps = [ep for when, mid, ep in lines if mid == fid and t0 <= when <= t1]
    return eps[0] if len(eps) == 1 else "?"


def verdict(t):
    run, line = t.get("run") or {}, t.get("line") or {}
    task = (t.get("llm") or {}).get("task") or {}
    if run.get("state") == "not_run":
        return "not run", run.get("why") or ""
    if run.get("state") != "ok":
        return "error", (run.get("error_line") or "")[:160]
    if line.get("pass") is None:
        return "no verdict", next((n["text"] for n in t.get("note") or [] if n.get("rank") == 2), "")
    basis = task.get("prompt_basis") or {}
    inst = (f"full text same {task.get('full_text_same')}/20, prompt "
            f"{'ids' if 'ids' in basis else 'token count'} same {task.get('prompt_ids_same')}/21, "
            f"end token within the maximum {task.get('eos_within_max')}/20")
    return ("PASS" if line["pass"] else "FAIL"), f"{line.get('text')} ({inst})"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--note", action="append", default=[], help="<model>/<Z2 cell>=<text>: a reason or remark")
    a = ap.parse_args()
    notes = dict(x.split("=", 1) for x in a.note)
    lines = []   # (time on the PC = JST, model id, EP)
    for x in (zoo.ROOT / EP_LINES).read_text(encoding="utf-8").splitlines():
        g = EP_LINE.match(x)
        if g:
            lines.append((datetime.datetime.fromisoformat(g[1] + "+09:00"), g[2], g[3]))
    by_ep = collections.defaultdict(list)
    rows, count = [], collections.Counter()
    by_rt = collections.defaultdict(collections.Counter)
    for m in MODELS:
        d = zoo.MODELS / m / "results"
        for p in sorted(d.glob("task-*.json")):
            t = json.loads(p.read_text(encoding="utf-8"))
            z2 = p.name[len("task-"):-len(".json")]
            c = json.loads((d / f"{z2}.json").read_text(encoding="utf-8"))
            ti = "PASS" if (c.get("line") or {}).get("pass") else "FAIL" if (c.get("line") or {}).get("pass") is False else "—"
            v, why = verdict(t)
            if t["runtime"]["id"] == "foundry":
                argv = (t.get("source") or {}).get("argv") or []
                env = [argv[i + 1] for i, x in enumerate(argv) if x == "--daemon-env"]
                by_ep[foundry_ep(t, lines)].append(f"{m} `{z2}`" + (f" (daemon {', '.join(env)})" if env else ""))
            count[v] += 1
            by_rt[t["runtime"]["label"]][v] += 1
            extra = notes.get(f"{m}/{z2}")
            rows.append(f"| {m} | `{z2}` | {t['runtime']['label']} | {t['device']['label']} | {ti} | **{v}** | "
                        f"{why.replace('|', '/')}{' — ' + extra if extra else ''} |")
    out = ["# The LLM cells that pass only the text-integrity line, judged on the qa20 task line", "",
           "Generated by `python3 tools/task_pairs_llm.py` from `models/*/results/` (do not edit, do not commit: it puts "
           "runtimes side by side). One line per copied cell: its "
           "text-integrity verdict (edge-llm-bench's textCheck, copied from the LLM zoo) and the verdict of its qa20 "
           "task cell `task-<cell>` (PLAN.md section Z6: 20 questions, the reference's rendered prompt passed as it is, "
           "greedy, at least 18 of 20 first lines the same as the reference's and the gate prompt ending on an end "
           "token within 16 new tokens; a first pass on the PC, untimed). The instruments in brackets do not decide "
           "the verdict.", "",
           f"Cells: {sum(count.values())}; qa20 " + ", ".join(f"{k} {v}" for k, v in sorted(count.items())), "",
           "| runtime | " + " | ".join(sorted({k for c in by_rt.values() for k in c})) + " |",
           "|---|" + "---|" * len({k for c in by_rt.values() for k in c})]
    keys = sorted({k for c in by_rt.values() for k in c})
    for rt in sorted(by_rt):
        out.append(f"| {rt} | " + " | ".join(str(by_rt[rt].get(k, 0)) for k in keys) + " |")
    out += ["", "| model | Z2 cell | runtime | device | text-integrity | qa20 | answers, gate (instruments) or why |",
            "|---|---|---|---|---|---|---|"] + rows
    if by_ep:
        out += ["", "## Notes", "",
                "- Foundry Local 0.13.0: where the daemon put each cell's main decoder (its log line inside the cell's "
                f"run, `{EP_LINES}`): " + "; ".join(f"{ep}: " + ", ".join(by_ep[ep]) for ep in sorted(by_ep)) + ". "
                "A `foundry_auto_webgpu` cell keeps Z2's name; with CUDA visible, the daemon puts a WebGPU package's "
                "main decoder on CUDA, as in Z2's runs of the three Qwen3 cells (the same log, 11-07 to 11-09). "
                "gemma-4-E2B-it's package does not load that way (WebGPU and CUDA in one model): its daemon starts "
                "with CUDA hidden, as the LLM zoo's timed run of that cell did (PLAN.md section Z6, change 8)."]
    zoo.write_text(zoo.ROOT / "TASK_PAIRS_LLM.md", "\n".join(out) + "\n")
    print(f"TASK_PAIRS_LLM.md: {len(rows)} lines; {dict(count)}")


if __name__ == "__main__":
    main()
