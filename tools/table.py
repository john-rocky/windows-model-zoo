ZOO_LICENCES = {  # a copied model's form-level licences (packages, exports) stay in its zoo's table
    "john-rocky/windows-zoo": "john-rocky/windows-zoo LICENSES.md",
    "john-rocky/windows-llm-zoo": "john-rocky/windows-llm-zoo LICENSES.md",
    "john-rocky/windows-audio-zoo": "john-rocky/windows-audio-zoo LICENSES.md",
}


def licences(models):
    rows = []
    for name, m in sorted(models.items(), key=lambda kv: kv[0].lower()):
        rec = m["recipe"]
        md = rec["model"]
        src, rev = md.get("source") or "", md.get("source_revision") or ""
        link = (f"[{src}](https://huggingface.co/{src}" + (f"/tree/{rev[:12]})" if rev else ")")) if "/" in src else (src or "—")
        mig = (md.get("migrated_from") or "").split("@")[0]
        forms = sorted(({f.get("from") for f in rec.get("form") or [] if f.get("from")} |
                        {x.get("repo") or x["url"].split("/")[3] + "/" + x["url"].split("/")[4]
                         for x in rec.get("fetch") or []}) - {src})
        where = ", ".join(forms) if forms else ""
        if mig:
            where = (where + "; " if where else "") + "the copied cells' forms: " + ZOO_LICENCES.get(mig, mig)
        rows.append([name, md["kind"], link, md.get("license") or "unverified", where or "—"])
    head = ("# Licences\n\nGenerated by `tools/table.py` from each recipe: `[model] license` = the source's licence "
            "(the Hub's `cardData.license`, read when the model was added or copied), the other repos its cells use, "
            "and for a copied model the zoo whose own table lists its forms' licences. Edit the recipes, not this file.\n\n"
            "## Models\n\n")
    t = md_table(["model", "kind", "source", "licence", "other repos its cells use (forms, tools)"], rows)
    used = {(m["recipe"].get("model") or {}).get("inputs") for m in models.values()}
    if any(m["recipe"]["model"]["kind"] == "llm" for m in models.values()):
        used.add("suites/llm/qa20.jsonl")
    if any(m["recipe"]["model"]["kind"] in ("asr", "tts") for m in models.values()):
        used.add("suites/audio/S150.json")
    sets = md_table(["input set", "what", "terms"], [[f"`{a}`", b, c] for a, b, c in INPUT_SETS if a in used])
    return head + t + "\n\n## Input sets\n\n" + sets + "\n"


LOCAL = ("RESULTS_VISION.md", "RESULTS_LLM.md", "RESULTS_ASR.md", "RESULTS_TTS.md", "models/index.json")


def render(models, local=True):
    """{path: text} of every generated file; the local ones (tables across runtimes, the index) only with local"""
    cfg = zoo.config()
    files = {}
    if local:
        kinds = {m["recipe"]["model"]["kind"] for m in models.values()}
        if "vision" in kinds:
            files["RESULTS_VISION.md"] = vision_tables(models, cfg)
        if "llm" in kinds:
            files["RESULTS_LLM.md"] = llm_tables(models, cfg)
        for k in ("asr", "tts"):
            if k in kinds:
                files[f"RESULTS_{k.upper()}.md"] = audio_tables(models, cfg, k)
        files["models/index.json"] = json.dumps(index(models), indent=1, ensure_ascii=False) + "\n"
    files["LICENSES.md"] = licences(models)
    for name, m in models.items():
        p = m["dir"] / "README.md"
        text = p.read_text(encoding="utf-8") if p.exists() else ""
        if BEGIN in text and END in text:
            a, b = text.index(BEGIN), text.index(END) + len(END)
            files[f"models/{name}/README.md"] = text[:a] + card_block(m) + text[b:]
    return files


def stale_files(files):
    """the generated files that differ from the disk; a local file counts only when it is on disk"""
    out = []
    for rel, text in files.items():
        p = zoo.ROOT / rel
        if rel in LOCAL and not p.exists():
            continue
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            out.append(rel)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--local", action="store_true", help="also write the tables across runtimes and the index")
    a = ap.parse_args()
    if a.check:
        stale = stale_files(render(load_all(), local=True))
        for s in stale:
            print(f"STALE {s}")
        sys.exit(1 if stale else 0)
    files = render(load_all(), local=a.local)
    n = 0
    for rel, text in files.items():
        p = zoo.ROOT / rel
        if (p.read_text(encoding="utf-8") if p.exists() else None) != text:
            zoo.write_text(p, text)
            n += 1
    print(f"wrote {n} of {len(files)} generated files" + ("" if a.local else
          " (the tables across runtimes: python3 tools/table.py --local, not committed)"))


if __name__ == "__main__":
    main()
