#!/usr/bin/env python3
"""Generate the cards' blocks and LICENSES.md (committed), and on request the tables and the index (local only),
from models/<model>/recipe.toml and models/<model>/results/<cell>.json.

    python3 tools/table.py            # write the cards' blocks and LICENSES.md
    python3 tools/table.py --local    # also write RESULTS_<KIND>.md and models/index.json (not committed: .gitignore)
    python3 tools/table.py --check    # write nothing; exit 1 when a generated file differs from what is on disk
                                      # (the local files only when they are on disk)

The text between `<!-- zoo:cells begin -->` and `<!-- zoo:cells end -->` in each card is this model's lines and where
its cells are: no cell is listed on a card. The local tables put the runtimes side by side, so they stay on your disk:
one file per kind (RESULTS_VISION.md, RESULTS_LLM.md, RESULTS_ASR.md, RESULTS_TTS.md); inside a file, one table per
(group, line kind, speed regime): a table never puts speeds of two regimes (QoS x MSI power mode) in one column, and
says which line its rows are judged on. A first-pass number (not a timing) is in brackets.
"""
import argparse
import collections
import datetime as dt
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import views  # noqa: E402
import zoo  # noqa: E402

BEGIN, END = "<!-- zoo:cells begin -->", "<!-- zoo:cells end -->"
LINE_WORDS = {"task": "the task line", "internal": "internal agreement", "text-integrity": "text integrity",
              "reference": "reference"}
COMPANION_ROLES = {"conversion-check", "other-device"}


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(x).replace("\n", " ") for x in r) + " |" for r in rows]
    return "\n".join(out)


def load_all():
    models = {}
    for d in zoo.model_dirs():
        models[d.name] = {"dir": d, "recipe": zoo.recipe(d), "cells": zoo.cells(d)}
    return models


def lines_of(recipe):
    return {l["id"]: l for l in recipe.get("line") or []}


def row_line(c):
    return c.get("row_line") or (c.get("line") or {}).get("id")


def regime_of(cells):
    keys = collections.Counter(zoo.regime_key(c) for c in cells
                               if c.get("role") not in COMPANION_ROLES and (c.get("speed") or {}).get("metric"))
    return keys.most_common(1)[0][0] if keys else ("unknown", "unrecorded")


def section_title(kind_words, line, regime, cfg, extra=""):
    lw = LINE_WORDS.get(line.get("kind"), line.get("kind")) if line else "no line"
    return (f"## {kind_words}{extra} — line: {lw} (`{line['id']}`) — speed: {zoo.regime_words(regime, cfg)}" if line
            else f"## {kind_words}{extra} — line: none — speed: {zoo.regime_words(regime, cfg)}")


def line_para(line):
    if not line:
        return ""
    rule = line["rule"].rstrip()
    rule += "" if rule.endswith(".") else "."
    return (f"Line `{line['id']}` ({LINE_WORDS.get(line['kind'], line['kind'])}): {rule} "
            f"Written {line['written']}" + (f" ({line['plan']})" if line.get("plan") else "") + ".")


# ---- vision ----

def vision_tables(models, cfg):
    tables = collections.OrderedDict()   # (group, line id, regime) -> rows
    meta = {}
    vm = sorted((m for m in models.values() if m["recipe"]["model"]["kind"] == "vision"),
                key=lambda m: (m["recipe"]["model"].get("order", 10 ** 6), m["dir"].name.lower()))
    task_cells, task_lines = [], collections.OrderedDict()   # the vision task cells (long view), each model's line
    for m in vm:
        rec = m["recipe"]
        long_ids = {c["id"] for c in rec.get("cell") or [] if c.get("script") == views.VISION_TASK_SCRIPT}
        parts = collections.OrderedDict()
        for c in m["cells"]:
            if c["cell"] in long_ids:
                task_cells.append((c, rec["model"].get("task")))
                task_lines.setdefault(m["dir"].name, lines_of(rec).get(row_line(c)))
                continue
            parts.setdefault(row_line(c), []).append(c)
        for lid, cs in parts.items():
            line = lines_of(rec).get(lid)
            group = rec["model"].get("group", "main")
            if line and line["kind"] == "task":
                group = "task"
            key = (group, lid if line and line["kind"] != "task" else "task", regime_of(cs))
            tables.setdefault(key, []).append(views.vision_row(m["dir"].name, rec, cs, group if group != "task" else "fixed"))
            meta[key] = line
    out = ["# Vision cells", "", "Generated by `tools/table.py` from `models/*/results/*.json` (do not edit). One row per "
           "model; the columns are cells (runtime x device). Times are ms per inference, host memory to host memory; "
           "a number in brackets is a first pass (not a timing); `-` = no number. Parity letters: a = Intel NPU as-is, "
           "p = Intel NPU precompiled, g = Intel GPU, h = RTX fp16, f = RTX fp32; P = pass, F = fail, E = did not run.", ""]
    titles = {"main": "Vision", "fixed": "Vision, the fixed conversions", "task": "Vision"}
    for (group, lid, regime), rows in tables.items():
        line = meta[(group, lid, regime)]
        out += [section_title(titles.get(group, group), line, regime, cfg), "", line_para(line), "",
                md_table(views.vision_header(group if group != "task" else "fixed"), rows), ""]
    out += vision_task_tables(task_cells, task_lines, vm, cfg)
    return "\n".join(out)


def vision_task_tables(task_cells, task_lines, vm, cfg):
    """The vision task cells, one row per cell, one table per speed regime (a cell nobody ran joins the largest);
    each model is judged on its own line, so the lines follow the tables, one per model."""
    if not task_cells:
        return []
    order = {m["dir"].name: m["recipe"]["model"].get("order", 10 ** 6) for m in vm}
    by = collections.OrderedDict()
    for c, task in task_cells:
        s = c.get("speed") or {}
        key = zoo.regime_key(c) if s.get("metric") and (c.get("run") or {}).get("state") != "not_run" else None
        by.setdefault(key, []).append((c, task))
    waiting = by.pop(None, [])
    if not by:
        by[("unknown", "unrecorded")] = []
    biggest = max(by, key=lambda k: len(by[k]))
    by[biggest] += waiting
    out = []
    for regime, cts in by.items():
        cts = sorted(cts, key=lambda ct: views.vision_task_sort_key(ct[0], order))
        out += [f"## Vision, the task cells — line: each model's task line (listed below) — speed: "
                f"{zoo.regime_words(regime, cfg)}", "",
                "One row per cell: each model on the task line of its own recipe, the reference = the same fp32 ONNX "
                "file on the ONNX Runtime CPU EP on the same inputs. `the line's numbers` = what the line counts, "
                "summed over the model's inputs; `no verdict` = the line has nothing to count (said in the numbers); "
                "a first-pass ms (in brackets) is the median of the inputs' single runs, not a timing.", "",
                md_table(views.VISION_TASK_HEADER, [views.vision_task_row(c, t) for c, t in cts]), ""]
    out += ["### The task lines of these cells", ""]
    for name in sorted(task_lines, key=lambda n: (order.get(n, 10 ** 6), n.lower())):
        out.append(f"- `{name}`: " + (line_para(task_lines[name]) or "no line"))
    out.append("")
    return out


# ---- llm ----

def ref_keys(models, cells):
    """one sentence: each model's reference answers right by the answer key (models/<model>/reference/ref.json key)"""
    parts = []
    for name in dict.fromkeys(c["model"] for c in cells):
        p = models[name]["dir"] / "reference" / "ref.json"
        k = json.loads(p.read_text(encoding="utf-8")).get("key") if p.exists() else None
        if k:
            parts.append(f"{name} {k['right']}/{k['n']}")
    return ("Answers right by the answer key (`suites/llm/qa20.key.jsonl`, `tools/qa20_key.py`; a count outside the line), "
            "the references: " + ", ".join(parts) + ".") if parts else ""


def llm_tables(models, cfg):
    order = {m["dir"].name: m["recipe"]["model"].get("order", 10 ** 6) for m in models.values()}
    by_key = collections.OrderedDict()
    meta = {}
    cells = [(m, c) for m in models.values() if m["recipe"]["model"]["kind"] == "llm" for c in m["cells"]]
    cells.sort(key=lambda mc: views.llm_sort_key(mc[1], order))
    for m, c in cells:
        line = lines_of(m["recipe"]).get(row_line(c))
        kind = (line or {}).get("kind", "none")
        key = (kind, line["id"] if line and kind != "task" else kind, zoo.regime_key(c))
        if (c.get("run") or {}).get("state") == "not_run":
            key = (kind, key[1], None)   # a cell nobody ran has no regime: it joins its line's first table
        by_key.setdefault(key, []).append(c)
        meta[key] = line
    # cells nobody ran go into the table of the same line with the most rows
    merged = collections.OrderedDict()
    for key, cs in by_key.items():
        if key[2] is None:
            continue
        merged[key] = list(cs)
    for key, cs in by_key.items():
        if key[2] is not None:
            continue
        target = max((k for k in merged if k[:2] == key[:2]), key=lambda k: len(merged[k]), default=None)
        if target is None:
            merged[key] = list(cs)
        else:
            merged[target] = sorted(merged[target] + cs, key=lambda c: views.llm_sort_key(c, order))
    out = ["# LLM cells", "", "Generated by `tools/table.py` from `models/*/results/*.json` (do not edit). One row per "
           "cell (model x runtime x device x package); 未 = not measured, with the reason.", ""]
    for key, cs in merged.items():
        line = meta.get(key) or next((meta[k] for k in meta if k[:2] == key[:2]), None)
        regime = key[2] or ("unknown", "unrecorded")
        out += [section_title("LLM", line, regime, cfg), "", line_para(line), ""]
        if key[0] == "task":
            refs = ref_keys(models, cs)
            if refs:
                out += [refs, ""]
            out.append(md_table(views.LLM_TASK_HEADER, [views.llm_task_row(c) for c in cs]))
        else:
            out.append(md_table(views.LLM_HEADER, [views.llm_row(c) for c in cs]))
        out.append("")
    return "\n".join(out)


# ---- asr / tts ----

def audio_tables(models, cfg, kind):
    order = {n: i for i, n in enumerate(views.AUDIO_MODEL_ORDER)}
    groups = collections.OrderedDict()
    meta = {}
    am = sorted((m for m in models.values() if m["recipe"]["model"]["kind"] == kind),
                key=lambda m: (order.get(m["dir"].name, 99), m["dir"].name.lower()))
    for m in am:
        own = [c for c in m["cells"] if not (c.get("audio") or {}).get("texts")]
        coll = [c for c in m["cells"] if (c.get("audio") or {}).get("texts")]
        for c in sorted(own, key=lambda c: c["cell"]) + sorted(coll, key=lambda c: c.get("sort_key") or c["cell"]):
            line = lines_of(m["recipe"]).get(row_line(c))
            a = c.get("audio") or {}
            key = (a.get("clipset") or a.get("set") or "?", (line or {}).get("id"), zoo.regime_key(c))
            groups.setdefault(key, []).append(c)
            meta[key] = line
    title = {"asr": "ASR", "tts": "TTS"}[kind]
    out = [f"# {title} cells", "", "Generated by `tools/table.py` from `models/*/results/*.json` (do not edit). One table "
           "per clip set, line and speed regime; RTF = processing wall time / audio seconds over the clips; a number in "
           "brackets is a first pass or a sitting whose control row did not pass (not a timing).", ""]
    for key, cs in groups.items():
        line = meta[key]
        out += [section_title(f"{title}, {key[0]}", line, key[2], cfg), "", line_para(line), "",
                md_table(views.AUDIO_HEADER, [views.audio_row(c) for c in cs]), ""]
    return "\n".join(out)


# ---- index and cards ----

def cell_summary(c, rec):
    line = lines_of(rec).get(row_line(c)) or {}
    s = c.get("speed") or {}
    return {"cell": c["cell"], "runtime": c["runtime"]["label"], "device": c["device"]["label"],
            "form": (c.get("form") or {}).get("label"), "state": (c.get("run") or {}).get("state"),
            "line": {"id": line.get("id"), "kind": (c.get("line") or {}).get("kind") or line.get("kind"),
                     "pass": (c.get("line") or {}).get("pass")},
            "speed": {"metric": s.get("metric"), "value": s.get("value"), "timed": s.get("timed")} if s else None,
            "regime": c.get("regime"), "result": f"models/{c['model']}/results/{c['cell']}.json"}


def index(models):
    out = []
    for name, m in sorted(models.items(), key=lambda kv: kv[0].lower()):
        rec = m["recipe"]
        md = rec["model"]
        out.append({"model": name, "kind": md["kind"], "card": f"models/{name}/README.md",
                    "recipe": f"models/{name}/recipe.toml", "source": md.get("source"),
                    "source_revision": md.get("source_revision"), "license": md.get("license"),
                    "lines": [{k: l.get(k) for k in ("id", "kind", "rule", "written")} for l in rec.get("line") or []],
                    "cells": [cell_summary(c, rec) for c in m["cells"]]})
    return {"generated_by": "tools/table.py", "how_to_use": "one entry per model directory; each cell names its result "
            "JSON (schema/cell.schema.json) and the line it is judged on", "models": out}


def card_block(m):
    """the model's lines and where its cells are; no cell is listed (a card never puts runtimes side by side)"""
    rec = m["recipe"]
    out = ["## Lines", ""]
    for l in rec.get("line") or []:
        p = line_para(l)
        if l.get("superseded_by"):
            p += f" Superseded by `{l['superseded_by']}`" + (f" ({l['superseded']})" if l.get("superseded") else "") + "."
        ref = m["dir"] / "reference" / "ref.json"
        k = json.loads(ref.read_text(encoding="utf-8")).get("key") if l["id"] == "qa20" and ref.exists() else None
        if k:
            p += (f" Answers right by the answer key (`suites/llm/qa20.key.jsonl`; a count outside the line, added on "
                  f"2026-11-10): the reference {k['right']} of {k['n']}; each `task-*` cell's count ends its `line.verdict` "
                  f"(PLAN.md, How to read the qa20 line).")
        out.append(f"- {p}")
    n = len(m["cells"])
    out += ["", f"## Cells", "",
            f"One JSON per cell (this model on one runtime, device and package) in [`results/`](results/): {n} files. "
            "Each one's `line.verdict` gives its verdict, its numbers and its line in one string; how the cell ran is "
            "in `recipe.toml` and in the run record the JSON names (`source.record`)."]
    return BEGIN + "\n" + "\n".join(out) + "\n" + END


